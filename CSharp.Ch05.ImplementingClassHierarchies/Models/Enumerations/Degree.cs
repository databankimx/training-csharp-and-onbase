namespace CSharp.Ch05.ImplementingClassHierarchies.Models.Enumerations
{
    /// <summary>
    /// Degree type for faculty
    /// </summary>
    public enum Degree
    {
        /// <summary>
        /// Associates degree, typically a two-year degree awarded by community colleges or technical schools.
        /// </summary>
        Associates,

        /// <summary>
        /// Represents a bachelor's degree, typically a four-year undergraduate degree awarded by colleges and universities.
        /// </summary>
        Bachelors,

        /// <summary>
        /// Masters degree, typically a graduate-level degree awarded after completing a bachelor's degree.
        /// </summary>
        Masters,

        /// <summary>
        /// Represents a doctorate degree, which is the highest level of academic degree awarded by universities,
        /// often requiring several years of research and study beyond a master's degree.
        /// </summary>
        Doctorate
    }
}

